import { createClient, type SupabaseClient } from '@supabase/supabase-js';
import { expect, test, type Page } from '@playwright/test';

import { loadE2eEnv, optionalEnv, requireEnv } from '../env';
import { type E2eState } from '../seed';
import { e2eState, loginAs, openTimetable } from './helpers';

/**
 * Candidate generation must be non-destructive: solving shows read-only
 * options while the live grid stays exactly as it was, and only Accept writes
 * drafts. A foreign-department auto-draft is seeded as a canary so an
 * over-broad clear is caught even when the E2E department has no auto-drafts.
 */
test.describe.configure({ mode: 'serial' });

const FOREIGN_DEPT_CODE = 'E2E-FGN';
const FOREIGN_DEPT_NAME = 'E2E Foreign Department';
const FOREIGN_REMARKS = 'Auto-generated by solver (foreign department fixture)';

type JsonRecord = Record<string, any>;
type Db = SupabaseClient<any, 'public', any>;
type LiveRow = JsonRecord & {
  scheduleId: string;
  deptId: string | null;
  status: string;
  remarks: string | null;
};

let state: E2eState;
let db: Db;
let foreignDeptId: string | null = null;
let foreignDraftId: string | null = null;

/** Call an app API with the Supabase token the browser stored at login. */
async function apiGet<T = JsonRecord>(
  page: Page,
  path: string,
  params?: Record<string, string>,
): Promise<T> {
  const token = await page.evaluate(() => {
    const key = Object.keys(localStorage).find((item) =>
      item.includes('auth-token'),
    );
    const raw = key ? localStorage.getItem(key) : null;
    if (!raw) return null;
    try {
      return (JSON.parse(raw) as JsonRecord).access_token ?? null;
    } catch {
      return null;
    }
  });
  if (!token) throw new Error('No Supabase access token in browser storage');

  const apiBase = optionalEnv(
    'E2E_API_URL',
    'http://127.0.0.1:3100/api',
  ).replace(/\/+$/, '');
  const response = await page.request.get(`${apiBase}${path}`, {
    headers: { Authorization: `Bearer ${token}` },
    ...(params ? { params } : {}),
  });
  expect(response.ok(), await response.text()).toBeTruthy();
  return ((await response.json()) as JsonRecord).data as T;
}

function liveRows(page: Page): Promise<LiveRow[]> {
  return apiGet<LiveRow[]>(page, '/v1/schedules', { termId: state.termId });
}

function generationResponse(page: Page) {
  return page.waitForResponse(
    (response) =>
      /\/v1\/schedules\/auto-generate\/?$/.test(
        new URL(response.url()).pathname,
      ) && response.request().method() === 'POST',
    { timeout: 180_000 },
  );
}

function confirmResponse(page: Page) {
  return page.waitForResponse(
    (response) =>
      /\/v1\/schedules\/auto-generate\/confirm\/?$/.test(
        new URL(response.url()).pathname,
      ) && response.request().method() === 'POST',
    { timeout: 60_000 },
  );
}

/** Recreate the foreign auto-draft canary from scratch for this spec. */
async function seedForeignDraft(): Promise<void> {
  const existing = await db
    .from('department')
    .select('dept_id')
    .eq('dept_code', FOREIGN_DEPT_CODE)
    .maybeSingle();
  if (existing.error) {
    throw new Error(`Could not find foreign department: ${existing.error.message}`);
  }

  if (existing.data) {
    foreignDeptId = String(existing.data.dept_id);
    const { error: clearError } = await db
      .from('schedule')
      .delete()
      .eq('term_id', state.termId)
      .eq('dept_id', foreignDeptId);
    if (clearError) {
      throw new Error(`Could not clear foreign draft: ${clearError.message}`);
    }
    const { error: activateError } = await db
      .from('department')
      .update({ is_active: true })
      .eq('dept_id', foreignDeptId);
    if (activateError) {
      throw new Error(`Could not activate foreign department: ${activateError.message}`);
    }
  } else {
    const { data, error } = await db
      .from('department')
      .insert({
        dept_code: FOREIGN_DEPT_CODE,
        dept_name: FOREIGN_DEPT_NAME,
        description: 'Disposable canary department for candidate E2E tests.',
        is_active: true,
      })
      .select('dept_id')
      .single();
    if (error || !data) {
      throw new Error(`Could not create foreign department: ${error?.message ?? 'none'}`);
    }
    foreignDeptId = String(data.dept_id);
  }

  const { data: draft, error } = await db
    .from('schedule')
    .insert({
      term_id: state.termId,
      subject_id: state.subjectId,
      faculty_id: state.facultyId,
      room_id: state.roomId,
      section: state.sectionCode,
      load_type: 'lecture',
      day_of_week: 'Tuesday',
      start_time: '08:00:00',
      end_time: '09:30:00',
      dept_id: foreignDeptId,
      status: 'draft',
      remarks: FOREIGN_REMARKS,
    })
    .select('schedule_id')
    .single();
  if (error || !draft) {
    throw new Error(`Could not seed foreign auto-draft: ${error?.message ?? 'none'}`);
  }
  foreignDraftId = String(draft.schedule_id);
}

async function removeForeignDraft(): Promise<void> {
  if (!db || !foreignDeptId) return;
  const { error: scheduleError } = await db
    .from('schedule')
    .delete()
    .eq('term_id', state.termId)
    .eq('dept_id', foreignDeptId);
  if (scheduleError) {
    throw new Error(`Could not remove foreign draft: ${scheduleError.message}`);
  }
  const { error: deptError } = await db
    .from('department')
    .delete()
    .eq('dept_id', foreignDeptId);
  if (deptError) {
    throw new Error(`Could not remove foreign department: ${deptError.message}`);
  }
}

function expectForeignDraftIntact(rows: LiveRow[]): void {
  const foreign = rows.find(
    (row) => String(row.scheduleId) === String(foreignDraftId),
  );
  expect(foreign, `foreign auto-draft ${foreignDraftId} was removed`).toBeTruthy();
  expect(foreign).toMatchObject({
    deptId: foreignDeptId,
    status: 'draft',
    remarks: FOREIGN_REMARKS,
  });
}

test.beforeAll(() => {
  loadE2eEnv();
  state = e2eState();
  db = createClient(
    requireEnv('E2E_SUPABASE_URL'),
    requireEnv('E2E_SUPABASE_SERVICE_ROLE_KEY'),
    { auth: { autoRefreshToken: false, persistSession: false } },
  );
  return seedForeignDraft();
});

test.afterAll(async () => {
  if (db) await removeForeignDraft();
});

test.beforeEach(async ({ page }) => {
  await page.route(/^https:\/\/fonts\.(googleapis|gstatic)\.com\//, (route) =>
    route.abort(),
  );
});

test('live grid stays unchanged until a candidate is accepted', async ({
  page,
}) => {
  test.setTimeout(300_000);

  await loginAs(page, 'head');
  await openTimetable(page);

  const beforeRows = await liveRows(page);
  expect(beforeRows.length).toBeGreaterThan(0);
  expectForeignDraftIntact(beforeRows);

  await page
    .getByLabel('Number of schedule options to generate')
    .selectOption('3');
  await expect(
    page.getByLabel('Number of schedule options to generate'),
  ).toHaveValue('3');

  const firstGeneration = generationResponse(page);
  await page.getByRole('button', { name: 'Auto-Generate' }).click();
  const generated = await firstGeneration;
  expect(generated.ok(), await generated.text()).toBeTruthy();

  const chooser = page.getByRole('heading', {
    name: 'Generated schedule options',
  });
  await expect(chooser).toBeVisible();
  const currentCard = page.getByRole('button', {
    name: /^Current live schedule/,
  });
  await expect(currentCard).toBeVisible();
  const optionCards = page.getByRole('button', { name: /^Option \d+/ });
  expect(await optionCards.count()).toBeGreaterThanOrEqual(2);
  await expect(
    page.getByRole('button', { name: 'Discard options' }),
  ).toBeVisible();

  // Solving and selecting are read-only; the API must still show the exact
  // same rows while the chooser is open.
  expect(await liveRows(page)).toEqual(beforeRows);
  await optionCards.first().click();
  await expect(
    page.getByRole('button', { name: /^Option 1/ }).first(),
  ).toHaveClass(/border-primary/);
  expect(await liveRows(page)).toEqual(beforeRows);

  const accepted = confirmResponse(page);
  await page.getByRole('button', { name: 'Use selected' }).click();
  const overwrite = page.getByRole('dialog', {
    name: 'Replace existing auto-generated drafts?',
  });
  const overwriteVisible = await overwrite
    .waitFor({ state: 'visible', timeout: 5_000 })
    .then(() => true)
    .catch(() => false);
  if (overwriteVisible) {
    await overwrite.getByRole('button', { name: 'Replace drafts' }).click();
  }
  const confirm = await accepted;
  expect(confirm.ok(), await confirm.text()).toBeTruthy();
  await expect(chooser).toBeHidden();

  const afterAccept = await liveRows(page);
  expect(afterAccept).not.toEqual(beforeRows);
  const beforeIds = new Set(beforeRows.map((row) => String(row.scheduleId)));
  const addedRows = afterAccept.filter(
    (row) => !beforeIds.has(String(row.scheduleId)),
  );
  expect(addedRows.length).toBeGreaterThan(0);
  for (const row of addedRows) {
    expect(String(row.deptId), JSON.stringify(row)).toBe(
      String(state.departmentId),
    );
    expect(row.status).toBe('draft');
    expect(String(row.remarks ?? '')).toMatch(
      /^Auto-generated by solver \(candidate /,
    );
  }
  expectForeignDraftIntact(afterAccept);

  // Keep current is a no-op: generate again, choose Current, and compare with
  // the exact post-accept snapshot rather than re-deriving expectations.
  const secondGeneration = generationResponse(page);
  await page.getByRole('button', { name: 'Auto-Generate' }).click();
  const regenerated = await secondGeneration;
  expect(regenerated.ok(), await regenerated.text()).toBeTruthy();
  await expect(chooser).toBeVisible();
  await expect(
    page.getByRole('button', { name: /^Current live schedule/ }),
  ).toBeVisible();
  await expect(
    page.getByRole('button', { name: /^Option \d+/ }).first(),
  ).toBeVisible();

  await currentCard.click();
  await expect(
    page.getByRole('button', { name: /^Current live schedule/ }),
  ).toHaveClass(/border-primary/);
  expect(await liveRows(page)).toEqual(afterAccept);
  await page.getByRole('button', { name: 'Keep current' }).click();
  await expect(chooser).toBeHidden();

  const afterKeep = await liveRows(page);
  expect(afterKeep).toEqual(afterAccept);
  expectForeignDraftIntact(afterKeep);
});
