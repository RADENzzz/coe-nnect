import {
  getScheduleDeptId,
  type ScheduleOwnershipRow,
} from '../../../api/schedule-ownership.ts';

type AutoGenerateScopeRow = ScheduleOwnershipRow & {
  status?: string | null;
  remarks?: string | null;
};

/**
 * Auto-generation lifecycle calls are department-scoped, but the schedule
 * list endpoint returns the whole term. Scope the rows before they become a
 * preview so another department's generated or plotted blocks never appear.
 */
export function scopeAutoGenerateRows<T extends AutoGenerateScopeRow>(
  rows: T[],
  deptId: string,
): T[] {
  if (!deptId) return [];
  const targetDeptId = String(deptId);
  return rows.filter((row) => getScheduleDeptId(row) === targetDeptId);
}

/** Count only this department's auto-generated drafts for the overwrite prompt. */
export function countAutoGenerateDrafts<T extends AutoGenerateScopeRow>(
  rows: T[],
  deptId: string,
): number {
  return scopeAutoGenerateRows(rows, deptId).filter(
    (row) =>
      row.status === 'draft' &&
      !!row.remarks?.startsWith('Auto-generated by solver'),
  ).length;
}
