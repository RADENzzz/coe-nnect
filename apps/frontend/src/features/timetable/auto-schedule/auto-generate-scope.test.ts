import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

import {
  countAutoGenerateDrafts,
  scopeAutoGenerateRows,
} from './auto-generate-scope.ts';

const read = (path: string) =>
  readFileSync(new URL(`../../../../../../${path}`, import.meta.url), 'utf8');

const autoDraft = (id: string, deptId: string | null, subjectDeptId: string) => ({
  scheduleId: id,
  deptId,
  subject: { deptId: subjectDeptId },
  status: 'draft',
  remarks: 'Auto-generated by solver (user e2e)',
});

test('auto-generate preview keeps only the generating department rows', () => {
  const own = autoDraft('1', '2', '1');
  const foreign = autoDraft('2', '1', '2');

  assert.deepEqual(scopeAutoGenerateRows([own, foreign], '2'), [own]);
});

test('auto-generate preview uses row ownership even for cross-department subjects', () => {
  const ownWithForeignCatalogSubject = autoDraft('1', '2', '1');
  const foreignWithOwnCatalogSubject = autoDraft('2', '1', '2');

  assert.deepEqual(
    scopeAutoGenerateRows(
      [ownWithForeignCatalogSubject, foreignWithOwnCatalogSubject],
      '2',
    ),
    [ownWithForeignCatalogSubject],
  );
});

test('auto-generate preview is empty without a department', () => {
  const own = autoDraft('1', '2', '2');

  assert.deepEqual(scopeAutoGenerateRows([own], ''), []);
});

test('overwrite count ignores other departments and manual drafts', () => {
  const ownAuto = autoDraft('1', '2', '2');
  const foreignAuto = autoDraft('2', '1', '2');
  const ownManual = {
    ...autoDraft('3', '2', '2'),
    remarks: 'Plotted manually',
  };

  assert.equal(
    countAutoGenerateDrafts([ownAuto, foreignAuto, ownManual], '2'),
    1,
  );
});

test('timetable preview and overwrite prompt use department-scoped helpers', () => {
  const page = read('apps/frontend/src/features/timetable/TimetablePage.tsx');

  assert.match(page, /scopeAutoGenerateRows\(/, 'preview must be dept-scoped');
  assert.doesNotMatch(
    page,
    /setAutoPreview\(fresh\.map\(toEntry\)\)/,
    'preview must not use the term-wide fetch directly',
  );
  assert.match(
    page,
    /countAutoGenerateDrafts\(/,
    'overwrite prompt must count only this department drafts',
  );
});
