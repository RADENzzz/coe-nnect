import 'reflect-metadata';
import { validate } from 'class-validator';
import { AutoGenerateDto } from '../src/modules/scheduling/dto/auto-generate.dto';
import { ConfirmAutoGenerateDto } from '../src/modules/scheduling/dto/confirm-auto-generate.dto';

const generateDto = (candidateCount?: number) =>
  Object.assign(new AutoGenerateDto(), {
    termId: '1',
    deptId: '2',
    ...(candidateCount === undefined ? {} : { candidateCount }),
  });

const confirmDto = (mode?: 'candidate') =>
  Object.assign(new ConfirmAutoGenerateDto(), {
    termId: '1',
    deptId: '2',
    ...(mode === undefined ? {} : { mode }),
  });

describe('phase two generate and confirm DTOs', () => {
  it('accepts omitted candidateCount and explicit 2, 3, 5', async () => {
    for (const dto of [
      generateDto(),
      generateDto(2),
      generateDto(3),
      generateDto(5),
    ]) {
      expect(await validate(dto)).toEqual([]);
    }
  });

  it('rejects explicit candidateCount 1 and 6', async () => {
    for (const candidateCount of [1, 6]) {
      const errors = await validate(generateDto(candidateCount));
      expect(errors.map((error) => error.property)).toContain(
        'candidateCount',
      );
    }
  });

  it('accepts legacy confirm body with no mode', async () => {
    expect(await validate(confirmDto())).toEqual([]);
  });

  it('requires generationToken and candidate when mode is candidate', async () => {
    const errors = await validate(confirmDto('candidate'));
    const properties = errors.map((error) => error.property);

    expect(properties).toContain('generationToken');
    expect(properties).toContain('candidate');
  });
});
