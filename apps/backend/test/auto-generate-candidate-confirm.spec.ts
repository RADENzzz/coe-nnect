import { BadRequestException, ConflictException } from '@nestjs/common';
import { AutoGenerateService } from '../src/modules/scheduling/services/auto-generate.service';
import {
  buildAutoGenerateToken,
  candidateFingerprint,
} from '../src/modules/scheduling/services/auto-generate-candidate.util';

describe('AutoGenerateService.confirmAutoGenerateCandidate', () => {
  const termId = '10';
  const deptId = '20';
  const userId = 'user-1';
  const generatedAt = '2026-11-27T10:00:00.000Z';

  const baseOwnDraftRows = [
    {
      schedule_id: 'draft-1',
      section_id: 'sec-1',
      subject_id: 'sub-1',
      load_type: 'lecture',
      day_of_week: 'Monday',
      start_time: '07:00:00',
      end_time: '08:00:00',
      room_id: 'room-1',
      faculty_id: 'fac-1',
      section: 'A',
      dept_id: deptId,
      term_id: termId,
      status: 'draft',
      remarks: 'Auto-generated by solver (old)',
    },
  ];

  const baseCandidate = {
    candidateId: 'cand-1',
    schedule: [
      {
        sectionId: 'sec-1',
        subjectId: 'sub-1',
        facultyId: 'fac-1',
        roomId: 'room-1',
        day: 'Monday',
        startTime: '08:00',
        endTime: '09:00',
        loadType: 'lecture' as const,
      },
    ],
    unscheduled: [],
  };

  function makeToken(ownRows = baseOwnDraftRows, ownUnscheduled: any[] = []) {
    const ownDraftBlocks = ownRows.map((r) => ({
      sectionId: String(r.section_id),
      subjectId: String(r.subject_id),
      loadType: r.load_type,
      day: String(r.day_of_week),
      startTime: String(r.start_time),
      endTime: String(r.end_time),
      roomId: String(r.room_id),
      facultyId: String(r.faculty_id),
      sectionCode: String(r.section),
    }));
    const fingerprint = candidateFingerprint(
      ownDraftBlocks,
      ownUnscheduled.map((r) => ({
        sectionId: String(r.section_id),
        subjectId: String(r.subject_id),
        kind: String(r.kind),
        sessionIndex: Number(r.session_index),
      })),
    );
    const hash = buildAutoGenerateToken({
      termId,
      deptId,
      userId,
      generatedAt,
      fingerprint,
    });
    // Self-contained token: confirm can extract generatedAt and still verify
    // the hash via verifyAutoGenerateToken.
    return `${Buffer.from(generatedAt, 'utf8').toString('base64url')}.${hash}`;
  }

  function makeRpc(overrides: Record<string, any> = {}) {
    return jest.fn(async (fn: string, _args?: any) => {
      if (overrides[fn]) return overrides[fn](fn, _args);
      if (fn === 'try_acquire_auto_generate_lock')
        return { data: true, error: null };
      if (fn === 'release_auto_generate_lock')
        return { data: true, error: null };
      return { data: null, error: null };
    });
  }

  type TableResponse = { data?: any; error?: any; count?: number };

  function makeFrom(tableResponses: Record<string, TableResponse[] | TableResponse> = {}) {
    const queues: Record<string, TableResponse[]> = {};
    for (const [table, value] of Object.entries(tableResponses)) {
      queues[table] = Array.isArray(value) ? [...value] : [value];
    }
    const calls: Record<string, any[]> = {};

    const from = jest.fn((table: string) => {
      calls[table] = calls[table] ?? [];
      const builder: any = {};
      const record = (op: string) => (...args: any[]) => {
        calls[table].push({ op, args });
        return builder;
      };
      builder.select = record('select');
      builder.insert = record('insert');
      builder.delete = record('delete');
      builder.eq = record('eq');
      builder.neq = record('neq');
      builder.in = record('in');
      builder.like = record('like');
      builder.or = record('or');
      builder.order = record('order');
      builder.maybeSingle = jest.fn(async () => {
        const queue = queues[table] ?? [];
        return queue.length > 0 ? queue.shift()! : { data: null, error: null };
      });
      builder.single = jest.fn(async () => {
        const queue = queues[table] ?? [];
        return queue.length > 0 ? queue.shift()! : { data: null, error: null };
      });
      builder.then = (resolve: any, reject: any) => {
        const queue = queues[table] ?? [];
        const response =
          queue.length > 0 ? queue.shift()! : { data: [], error: null, count: 0 };
        return Promise.resolve(response).then(resolve, reject);
      };
      return builder;
    });

    return { from, calls };
  }

  function makeService(options: {
    rpc?: any;
    tableResponses?: Record<string, TableResponse[] | TableResponse>;
    ownRows?: any[];
    ownUnscheduled?: any[];
    validation?: { hardFailures: any[]; softWarnings: any[] };
  } = {}) {
    const rpc = options.rpc ?? makeRpc();
    const { from, calls } = makeFrom(options.tableResponses ?? {});
    const db = { from, rpc };
    const supabase = { getAdminClient: jest.fn(() => db) };

    const service = new AutoGenerateService(
      supabase as any,
      { solve: jest.fn() } as any,
      { evaluate: jest.fn() } as any,
      { build: jest.fn() } as any,
      { findUnplottedMinors: jest.fn() } as any,
      { dispatch: jest.fn().mockResolvedValue(undefined) } as any,
      {
        departmentHeadsOf: jest.fn().mockResolvedValue([]),
        administrators: jest.fn().mockResolvedValue([]),
        collegeDean: jest.fn().mockResolvedValue([]),
        uniq: jest.fn((arr: string[]) => Array.from(new Set(arr))),
      } as any,
      { assertDepartmentActive: jest.fn().mockResolvedValue(undefined) } as any,
    );

    const ownRows = options.ownRows ?? baseOwnDraftRows;
    const ownUnscheduled = options.ownUnscheduled ?? [];

    jest
      .spyOn(service as any, 'getOwnAutoDraftScheduleRows')
      .mockResolvedValue(ownRows);
    jest
      .spyOn(service as any, 'getOwnAutoDraftUnscheduledRows')
      .mockResolvedValue(ownUnscheduled);
    jest
      .spyOn(service as any, 'validateGeneratedSchedule')
      .mockResolvedValue(
        options.validation ?? { hardFailures: [], softWarnings: [] },
      );

    return { service, supabase, db, from, calls, rpc };
  }

  it('rejects a stale generationToken with 409 and writes nothing', async () => {
    const { service, from } = makeService();
    const staleToken = makeToken([
      {
        ...baseOwnDraftRows[0],
        day_of_week: 'Tuesday', // different from current snapshot
      },
    ]);

    await expect(
      service.confirmAutoGenerateCandidate(termId, deptId, userId, {
        generationToken: staleToken,
        candidate: baseCandidate as any,
      }),
    ).rejects.toBeInstanceOf(ConflictException);

    const scheduleWrites = (from.mock.calls as any[])
      .filter(([table]) => table === 'schedule')
      .length;
    expect(scheduleWrites).toBe(0);
  });

  it('rejects when the accept lock cannot be acquired with 409 and writes nothing', async () => {
    const rpc = makeRpc({
      try_acquire_auto_generate_lock: async () => ({ data: false, error: null }),
    });
    const { service, from } = makeService({ rpc });
    const token = makeToken();

    await expect(
      service.confirmAutoGenerateCandidate(termId, deptId, userId, {
        generationToken: token,
        candidate: baseCandidate as any,
      }),
    ).rejects.toBeInstanceOf(ConflictException);

    const scheduleWrites = (from.mock.calls as any[])
      .filter(([table]) => table === 'schedule')
      .length;
    expect(scheduleWrites).toBe(0);
  });

  it('rejects source-dept subjects with 400 and writes nothing', async () => {
    const { service, from } = makeService({
      tableResponses: {
        subject: { data: [{ subject_id: 'sub-1', source_dept: 'EE' }], error: null },
      },
    });
    const token = makeToken();

    await expect(
      service.confirmAutoGenerateCandidate(termId, deptId, userId, {
        generationToken: token,
        candidate: baseCandidate as any,
      }),
    ).rejects.toBeInstanceOf(BadRequestException);

    expect(from).not.toHaveBeenCalledWith('schedule');
  });

  it('rejects duplicate or overlapping candidate blocks with 400 and writes nothing', async () => {
    const { service, from } = makeService({
      tableResponses: {
        subject: { data: [{ subject_id: 'sub-1', source_dept: null }], error: null },
      },
    });
    const token = makeToken();
    const overlappingCandidate = {
      candidateId: 'cand-dup',
      schedule: [
        { ...baseCandidate.schedule[0] },
        {
          ...baseCandidate.schedule[0],
          facultyId: 'fac-2',
          roomId: 'room-2',
          startTime: '08:30',
          endTime: '09:30',
        },
      ],
      unscheduled: [],
    };

    await expect(
      service.confirmAutoGenerateCandidate(termId, deptId, userId, {
        generationToken: token,
        candidate: overlappingCandidate as any,
      }),
    ).rejects.toBeInstanceOf(BadRequestException);

    expect(from).not.toHaveBeenCalledWith('schedule');
  });

  it('replaces only own auto drafts and stamps accepted rows with the generating dept', async () => {
    const snapshotRows = [
      { ...baseOwnDraftRows[0] },
      {
        ...baseOwnDraftRows[0],
        schedule_id: 'draft-2',
        section_id: 'sec-2',
        subject_id: 'sub-2',
        section: 'B',
      },
    ];

    const deleteCalls: any[] = [];
    const insertCalls: any[] = [];
    const from = jest.fn((table: string) => {
      const builder: any = {};
      const chain = (op: string) => (...args: any[]) => {
        if (table === 'schedule' && op === 'delete') deleteCalls.push(args);
        if (table === 'schedule' && op === 'insert') insertCalls.push(args);
        return builder;
      };
      builder.select = chain('select');
      builder.insert = chain('insert');
      builder.delete = chain('delete');
      builder.eq = chain('eq');
      builder.neq = chain('neq');
      builder.in = chain('in');
      builder.like = chain('like');
      builder.or = chain('or');
      builder.maybeSingle = jest.fn(async () => ({ data: null, error: null }));
      builder.then = (resolve: any, reject: any) => {
        if (table === 'subject') {
          return Promise.resolve({
            data: [{ subject_id: 'sub-1', source_dept: null }],
            error: null,
          }).then(resolve, reject);
        }
        if (table === 'schedule' && insertCalls.length > 0) {
          return Promise.resolve({ data: [{ schedule_id: 'new-1' }], error: null }).then(
            resolve,
            reject,
          );
        }
        return Promise.resolve({ data: [], error: null }).then(resolve, reject);
      };
      return builder;
    });
    const rpc = makeRpc();
    const db = { from, rpc };
    const supabase = { getAdminClient: jest.fn(() => db) };

    const service = new AutoGenerateService(
      supabase as any,
      { solve: jest.fn() } as any,
      { evaluate: jest.fn() } as any,
      { build: jest.fn() } as any,
      { findUnplottedMinors: jest.fn() } as any,
      { dispatch: jest.fn().mockResolvedValue(undefined) } as any,
      {
        departmentHeadsOf: jest.fn().mockResolvedValue([]),
        administrators: jest.fn().mockResolvedValue([]),
        collegeDean: jest.fn().mockResolvedValue([]),
        uniq: jest.fn((arr: string[]) => Array.from(new Set(arr))),
      } as any,
      { assertDepartmentActive: jest.fn().mockResolvedValue(undefined) } as any,
    );

    jest.spyOn(service as any, 'getOwnAutoDraftScheduleRows').mockResolvedValue(snapshotRows);
    jest.spyOn(service as any, 'getOwnAutoDraftUnscheduledRows').mockResolvedValue([]);
    jest.spyOn(service as any, 'validateGeneratedSchedule').mockResolvedValue({
      hardFailures: [],
      softWarnings: [],
    });

    const token = makeToken(snapshotRows);
    await service.confirmAutoGenerateCandidate(termId, deptId, userId, {
      generationToken: token,
      candidate: baseCandidate as any,
    });

    expect(insertCalls.length).toBeGreaterThan(0);
    const insertedRows = insertCalls[0][0];
    const rows = Array.isArray(insertedRows) ? insertedRows : [insertedRows];
    expect(rows[0].dept_id).toBe(deptId);
    expect(rows[0].status).toBe('draft');
    expect(String(rows[0].remarks)).toMatch(/^Auto-generated by solver \(candidate /);
    expect(deleteCalls.length).toBeGreaterThan(0);
  });

  it('restores the own auto draft snapshot when insert fails', async () => {
    const snapshotRows = [{ ...baseOwnDraftRows[0] }];
    const insertCalls: any[] = [];
    const deleteCalls: any[] = [];
    const from = jest.fn((table: string) => {
      const builder: any = {};
      let selected = false;
      const chain = (op: string) =>
        jest.fn((...args: any[]) => {
          if (op === 'select') selected = true;
          if (table === 'schedule' && op === 'insert') insertCalls.push(args);
          if (table === 'schedule' && op === 'delete') deleteCalls.push(args);
          return builder;
        });
      builder.select = chain('select');
      builder.insert = chain('insert');
      builder.delete = chain('delete');
      builder.eq = chain('eq');
      builder.neq = chain('neq');
      builder.in = chain('in');
      builder.like = chain('like');
      builder.or = chain('or');
      builder.maybeSingle = jest.fn(async () => ({ data: null, error: null }));
      builder.then = (resolve: any, reject: any) => {
        if (table === 'subject') {
          return Promise.resolve({
            data: [{ subject_id: 'sub-1', source_dept: null }],
            error: null,
          }).then(resolve, reject);
        }
        if (table === 'schedule' && builder.insert.mock.calls.length > 0) {
          // first insert is candidate insert -> fail, second is restore -> succeed
          if (insertCalls.length === 1) {
            return Promise.resolve({
              data: null,
              error: { message: 'insert failed' },
            }).then(resolve, reject);
          }
          return Promise.resolve({ data: snapshotRows, error: null }).then(
            resolve,
            reject,
          );
        }
        if (table === 'schedule' && selected && builder.delete.mock.calls.length === 0) {
          return Promise.resolve({ data: snapshotRows, error: null }).then(
            resolve,
            reject,
          );
        }
        return Promise.resolve({ data: [], error: null }).then(resolve, reject);
      };
      return builder;
    });
    const rpc = makeRpc();
    const db = { from, rpc };
    const supabase = { getAdminClient: jest.fn(() => db) };

    const service = new AutoGenerateService(
      supabase as any,
      { solve: jest.fn() } as any,
      { evaluate: jest.fn() } as any,
      { build: jest.fn() } as any,
      { findUnplottedMinors: jest.fn() } as any,
      { dispatch: jest.fn().mockResolvedValue(undefined) } as any,
      {
        departmentHeadsOf: jest.fn().mockResolvedValue([]),
        administrators: jest.fn().mockResolvedValue([]),
        collegeDean: jest.fn().mockResolvedValue([]),
        uniq: jest.fn((arr: string[]) => Array.from(new Set(arr))),
      } as any,
      { assertDepartmentActive: jest.fn().mockResolvedValue(undefined) } as any,
    );

    jest.spyOn(service as any, 'getOwnAutoDraftScheduleRows').mockResolvedValue(snapshotRows);
    jest.spyOn(service as any, 'getOwnAutoDraftUnscheduledRows').mockResolvedValue([]);
    jest.spyOn(service as any, 'validateGeneratedSchedule').mockResolvedValue({
      hardFailures: [],
      softWarnings: [],
    });

    const token = makeToken(snapshotRows);
    await expect(
      service.confirmAutoGenerateCandidate(termId, deptId, userId, {
        generationToken: token,
        candidate: baseCandidate as any,
      }),
    ).rejects.toBeTruthy();

    // At least one restore insert attempted after the failed candidate insert.
    expect(insertCalls.length).toBeGreaterThanOrEqual(2);
    expect(deleteCalls.length).toBeGreaterThanOrEqual(2); // clear own drafts + delete partial by marker
  });

  it('does not persist the client unscheduled list', async () => {
    const insertTables: string[] = [];
    const from = jest.fn((table: string) => {
      const builder: any = {};
      const chain = (op: string) => (...args: any[]) => {
        if (op === 'insert') insertTables.push(table);
        return builder;
      };
      builder.select = chain('select');
      builder.insert = chain('insert');
      builder.delete = chain('delete');
      builder.eq = chain('eq');
      builder.neq = chain('neq');
      builder.in = chain('in');
      builder.like = chain('like');
      builder.or = chain('or');
      builder.maybeSingle = jest.fn(async () => ({ data: null, error: null }));
      builder.then = (resolve: any, reject: any) => {
        if (table === 'subject') {
          return Promise.resolve({
            data: [{ subject_id: 'sub-1', source_dept: null }],
            error: null,
          }).then(resolve, reject);
        }
        if (table === 'schedule') {
          return Promise.resolve({ data: [{ schedule_id: 'new-1' }], error: null }).then(
            resolve,
            reject,
          );
        }
        return Promise.resolve({ data: [], error: null }).then(resolve, reject);
      };
      return builder;
    });
    const rpc = makeRpc();
    const db = { from, rpc };
    const supabase = { getAdminClient: jest.fn(() => db) };

    const service = new AutoGenerateService(
      supabase as any,
      { solve: jest.fn() } as any,
      { evaluate: jest.fn() } as any,
      { build: jest.fn() } as any,
      { findUnplottedMinors: jest.fn() } as any,
      { dispatch: jest.fn().mockResolvedValue(undefined) } as any,
      {
        departmentHeadsOf: jest.fn().mockResolvedValue([]),
        administrators: jest.fn().mockResolvedValue([]),
        collegeDean: jest.fn().mockResolvedValue([]),
        uniq: jest.fn((arr: string[]) => Array.from(new Set(arr))),
      } as any,
      { assertDepartmentActive: jest.fn().mockResolvedValue(undefined) } as any,
    );

    jest.spyOn(service as any, 'getOwnAutoDraftScheduleRows').mockResolvedValue(baseOwnDraftRows);
    jest.spyOn(service as any, 'getOwnAutoDraftUnscheduledRows').mockResolvedValue([]);
    jest.spyOn(service as any, 'validateGeneratedSchedule').mockResolvedValue({
      hardFailures: [],
      softWarnings: [],
    });

    const token = makeToken();
    await service.confirmAutoGenerateCandidate(termId, deptId, userId, {
      generationToken: token,
      candidate: {
        ...baseCandidate,
        unscheduled: [
          {
            sectionId: 'sec-1',
            subjectId: 'sub-2',
            kind: 'lecture',
            sessionIndex: 0,
          },
        ],
      } as any,
    });

    expect(insertTables).not.toContain('schedule_unscheduled');
  });
});
