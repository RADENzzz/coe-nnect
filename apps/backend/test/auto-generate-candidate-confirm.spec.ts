  function rpcCalls(rpc: jest.Mock, fn: string) {
    return rpc.mock.calls.filter(([name]: [string]) => name === fn);
  }

  // Default RPC mock emulates CI's migrated schema: only term-scoped lock
  // signatures exist, so a dept-scoped payload gets PostgREST's PGRST202.
  function makeRpc(overrides: Record<string, any> = {}) {
    return jest.fn(async (fn: string, args?: any) => {
      if (overrides[fn]) return overrides[fn](fn, args);
      if (
        lockFunctions.has(fn) &&
        args &&
        Object.prototype.hasOwnProperty.call(args, 'p_dept_id')
      ) {
        return missingFunctionError(fn);
      }
      if (fn === 'try_acquire_auto_generate_lock')
        return { data: true, error: null };
      if (fn === 'release_auto_generate_lock')
        return { data: true, error: null };
      return { data: null, error: null };
    });
  }

  type TableResponse = { data?: any; error?: any; count?: number };

  function makeFrom(tableResponses: Record<string, TableResponse[] | TableResponse> = {}) {
    const queues: Record<string, TableResponse[]> = {};
    for (const [table, value] of Object.entries(tableResponses)) {
      queues[table] = Array.isArray(value) ? [...value] : [value];
    }
    const calls: Record<string, any[]> = {};

    const from = jest.fn((table: string) => {
      calls[table] = calls[table] ?? [];
      const builder: any = {};
      const record = (op: string) => (...args: any[]) => {
        calls[table].push({ op, args });
        return builder;
      };
      builder.select = record('select');
      builder.insert = record('insert');
      builder.delete = record('delete');
      builder.eq = record('eq');
      builder.neq = record('neq');
      builder.in = record('in');
      builder.like = record('like');
      builder.or = record('or');
      builder.order = record('order');
      builder.maybeSingle = jest.fn(async () => {
        const queue = queues[table] ?? [];
        return queue.length > 0 ? queue.shift()! : { data: null, error: null };
      });
      builder.single = jest.fn(async () => {
        const queue = queues[table] ?? [];
        return queue.length > 0 ? queue.shift()! : { data: null, error: null };
      });
      builder.then = (resolve: any, reject: any) => {
        const queue = queues[table] ?? [];
        const response =
          queue.length > 0 ? queue.shift()! : { data: [], error: null, count: 0 };
        return Promise.resolve(response).then(resolve, reject);
      };
      return builder;
    });

    return { from, calls };
  }

