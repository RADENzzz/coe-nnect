import { SchedulingController } from '../src/modules/scheduling/scheduling.controller';
import { AutoGenerateDto } from '../src/modules/scheduling/dto/auto-generate.dto';

/**
 * Routing-level regression: the browser sends `candidateCount` so the service
 * can enter non-destructive candidate mode. Dropping it here silently sends
 * every request down the legacy destructive path instead.
 */
describe('SchedulingController.autoGenerate options', () => {
  const termId = '10';
  const deptId = '20';
  const userId = 'user-1';
  const result = { success: true };

  function makeController() {
    const service = { autoGenerate: jest.fn().mockResolvedValue(result) };
    const controller = new SchedulingController(service as any);
    const req = {
      user: { id: userId },
      profile: { role: 'department_head', deptId },
    };
    return { service, controller, req };
  }

  it('forwards candidateCount and the acknowledge flag for a department head', async () => {
    const { service, controller, req } = makeController();
    const dto = {
      termId,
      // A head's own department wins over any body override.
      deptId: '999',
      acknowledgeUnplottedMinors: false,
      candidateCount: 3,
    } as AutoGenerateDto;

    await expect(controller.autoGenerate(dto, req)).resolves.toEqual({
      data: result,
    });
    expect(service.autoGenerate).toHaveBeenCalledTimes(1);
    expect(service.autoGenerate).toHaveBeenCalledWith(termId, deptId, userId, {
      acknowledgeUnplottedMinors: false,
      candidateCount: 3,
    });
  });

  it('preserves a true acknowledge flag alongside candidateCount', async () => {
    const { service, controller, req } = makeController();
    const dto = {
      termId,
      deptId: String(deptId),
      acknowledgeUnplottedMinors: true,
      candidateCount: 5,
    } as AutoGenerateDto;

    await controller.autoGenerate(dto, req);
    expect(service.autoGenerate).toHaveBeenCalledWith(termId, deptId, userId, {
      acknowledgeUnplottedMinors: true,
      candidateCount: 5,
    });
  });

  it('forwards undefined candidateCount for legacy requests', async () => {
    const { service, controller, req } = makeController();
    const dto = {
      termId,
      deptId: String(deptId),
      acknowledgeUnplottedMinors: false,
    } as AutoGenerateDto;

    await expect(controller.autoGenerate(dto, req)).resolves.toEqual({
      data: result,
    });
    expect(service.autoGenerate).toHaveBeenCalledTimes(1);
    expect(service.autoGenerate).toHaveBeenCalledWith(termId, deptId, userId, {
      acknowledgeUnplottedMinors: false,
      candidateCount: undefined,
    });
  });
});
