import { IsString, IsNotEmpty, IsOptional, IsBoolean } from 'class-validator';

export class AutoGenerateDto {
  @IsString()
  @IsNotEmpty()
  termId!: string;

  @IsString()
  @IsNotEmpty()
  deptId!: string;

  /**
   * Skip the "unplotted minors" pre-flight check.
   *
   * By default, auto-generate refuses to run when the prospectus contains
   * minor subjects (subject.is_minor = true) that have no schedule rows
   * yet — because those are treated as fixed obstacles, and generating
   * without them would place department subjects in slots the minors
   * would later need.
   *
   * Set to true to override and generate anyway (the DH acknowledges the
   * risk).
   */
  @IsOptional()
  @IsBoolean()
  acknowledgeUnplottedMinors?: boolean;
}