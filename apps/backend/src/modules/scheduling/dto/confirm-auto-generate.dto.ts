import { Type } from 'class-transformer';
import {
  IsArray,
  IsDefined,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  ValidateIf,
  ValidateNested,
} from 'class-validator';

/**
 * A single placed block from a generated candidate. The whole payload is
 * untrusted: the confirm service re-checks every row against the catalog and
 * live schedule before writing, but the DTO rejects structurally invalid rows
 * at the request boundary.
 */
export class ConfirmCandidateBlockDto {
  @IsString()
  @IsNotEmpty()
  sectionId!: string;

  /** Solver-extracted blocks carry it; confirm accepts it when present. */
  @IsOptional()
  @IsString()
  sectionCode?: string;

  @IsString()
  @IsNotEmpty()
  subjectId!: string;

  @IsString()
  @IsNotEmpty()
  facultyId!: string;

  @IsString()
  @IsNotEmpty()
  roomId!: string;

  @IsString()
  @IsNotEmpty()
  day!: string;

  @IsString()
  @IsNotEmpty()
  startTime!: string;

  @IsString()
  @IsNotEmpty()
  endTime!: string;

  @IsIn(['lecture', 'laboratory'])
  loadType!: 'lecture' | 'laboratory';
}

/** Client-side waiting list; never persisted by confirm. */
export class ConfirmUnscheduledDto {
  @IsString()
  @IsNotEmpty()
  sectionId!: string;

  @IsOptional()
  @IsString()
  sectionCode?: string;

  @IsString()
  @IsNotEmpty()
  subjectId!: string;

  @IsOptional()
  @IsString()
  subjectCode?: string;

  @IsString()
  @IsNotEmpty()
  kind!: string;

  @IsInt()
  sessionIndex!: number;
}

export class ConfirmCandidateDto {
  @IsString()
  @IsNotEmpty()
  candidateId!: string;

  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => ConfirmCandidateBlockDto)
  schedule!: ConfirmCandidateBlockDto[];

  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => ConfirmUnscheduledDto)
  unscheduled!: ConfirmUnscheduledDto[];
}

const isCandidateMode = (dto: ConfirmAutoGenerateDto): boolean =>
  dto?.mode === 'candidate';

/**
 * Legacy bodies ({ termId, deptId }) still validate and still take the legacy
 * confirm path. Candidate bodies must carry the token and the full selected
 * candidate; the stored candidate payload is intentionally server-side free.
 */
export class ConfirmAutoGenerateDto {
  @IsString()
  @IsNotEmpty()
  termId!: string;

  @IsOptional()
  @IsString()
  deptId?: string;

  @IsOptional()
  @IsIn(['candidate'])
  mode?: 'candidate';

  @ValidateIf(isCandidateMode)
  @IsString()
  @IsNotEmpty()
  generationToken?: string;

  @ValidateIf(isCandidateMode)
  @IsDefined()
  @ValidateNested()
  @Type(() => ConfirmCandidateDto)
  candidate?: ConfirmCandidateDto;
}

/** What the controller hands to SchedulingService.confirmAutoGenerateCandidate. */
export type ConfirmCandidatePayload = Pick<
  ConfirmAutoGenerateDto,
  'generationToken' | 'candidate'
>;
