// apps/backend/src/modules/scheduling/scheduling.controller.ts
import {
  BadRequestException,
  Body,
  Controller,
  Delete,
  Get,
  Param,
  Patch,
  Post,
  Query,
  Req,
  UseGuards,
} from '@nestjs/common';
import { ApiTags, ApiBearerAuth } from '@nestjs/swagger';
import { SchedulingService } from './scheduling.service';
import { PlotSubjectDto } from './dto/plot-subject.dto';
import { UpdateScheduleDto } from './dto/update-schedule.dto';
import { JwtAuthGuard } from '../../common/guards/jwt-auth.guard';
import { RolesGuard } from '../../common/guards/roles.guard';
import { ValidatePlotDto } from './dto/validate-plot.dto';
import { UpdateRemarksDto } from './dto/update-remarks.dto';
import { UpdateStatusDto } from './dto/update-status.dto';
import { Roles } from '../../common/decorators/roles.decorator';
import { Auditable } from '../../common/decorators/auditable.decorator';
import { AutoGenerateDto } from './dto/auto-generate.dto';
import { FlagScheduleDto } from './dto/flag-schedule.dto';
import { PlotMultiDto } from './dto/plot-multi.dto';

@ApiTags('Scheduling')
@ApiBearerAuth('supabase-jwt')
@UseGuards(JwtAuthGuard, RolesGuard)
@Controller('v1/schedules')
export class SchedulingController {
  constructor(private service: SchedulingService) {}

  // ═══════════════════════════════════════════════════════════
  // STATIC-PREFIX ROUTES
  // ═══════════════════════════════════════════════════════════

  @Get('unscheduled')
  async getUnscheduled(@Query('termId') termId: string) {
    const data = await this.service.getUnscheduled(termId);
    return { data };
  }

  @Get('flagged')
  @Roles('college_dean', 'department_head')
  async findFlagged(
    @Query('termId') termId: string,
    @Req() req: any,
  ) {
    const data = await this.service.findFlagged(termId, req.profile);
    return { data };
  }

  @Get('unplotted-minors')
  @Roles('college_dean', 'department_head')
  async unplottedMinors(
    @Query('termId') termId: string,
    @Query('deptId') deptId: string,
  ) {
    const data = await this.service.findUnplottedMinors(termId, deptId);
    return { data };
  }

  @Get('coverage')
  @Roles('college_dean', 'department_head')
  async coverage(
    @Query('termId') termId: string,
    @Query('deptId') deptId: string,
  ) {
    const data = await this.service.getCoverage(termId, deptId);
    return { data };
  }

  @Get('active-term')
  async getActiveTerm() {
    const data = await this.service.getActiveTerm();
    return { data };
  }

  @Post('validate')
  async validate(@Body() dto: ValidatePlotDto) {
    const data = await this.service.validate(dto);
    return { data };
  }

  @Auditable({ action: 'schedule.create', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('plot')
  async plot(@Body() dto: PlotSubjectDto, @Req() req: any) {
    const data = await this.service.plot(dto, req.profile);
    return { data };
  }

  @Auditable({ action: 'schedule.plot_multi', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('plot-multi')
  async plotMulti(@Body() dto: PlotMultiDto, @Req() req: any) {
    const data = await this.service.plotMulti(dto, req.profile);
    return { data };
  }

  @Auditable({ action: 'schedule.auto_generate', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('auto-generate')
  async autoGenerate(@Body() dto: AutoGenerateDto, @Req() req: any) {
    const deptId = this.resolveDeptId(req, dto.deptId);
    const data = await this.service.autoGenerate(
      dto.termId,
      deptId,
      req.user.id,
      { acknowledgeUnplottedMinors: dto.acknowledgeUnplottedMinors === true },
    );
    return { data };
  }

  @Auditable({ action: 'schedule.auto_abandon', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('auto-generate/abandon')
  async abandonAutoGenerate(
    @Body('termId') termId: string,
    @Body('deptId') bodyDeptId: string | undefined,
    @Req() req: any,
  ) {
    const deptId = this.resolveDeptId(req, bodyDeptId);
    await this.service.abandonAutoGenerate(termId, deptId, req.user.id);
    return { data: { success: true } };
  }

  @Auditable({ action: 'schedule.auto_confirm', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('auto-generate/confirm')
  async confirmAutoGenerate(
    @Body('termId') termId: string,
    @Body('deptId') bodyDeptId: string | undefined,
    @Req() req: any,
  ) {
    const deptId = this.resolveDeptId(req, bodyDeptId);
    await this.service.confirmAutoGenerate(termId, deptId, req.user.id);
    return { data: { success: true } };
  }

  @Get('auto-generate/pending')
  @Roles('college_dean', 'department_head')
  async getPendingAutoGenerate(
    @Query('termId') termId: string,
    @Query('deptId') queryDeptId: string | undefined,
    @Req() req: any,
  ) {
    const deptId = this.resolveDeptId(req, queryDeptId);
    const data = await this.service.getAutoGenerateLock(
      termId,
      deptId,
      req.user.id,
    );
    return { data };
  }

  @Auditable({ action: 'schedule.auto_discard', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post('auto-generate/discard')
  async discardAutoGenerate(
    @Body('termId') termId: string,
    @Body('deptId') bodyDeptId: string | undefined,
    @Req() req: any,
  ) {
    const deptId = this.resolveDeptId(req, bodyDeptId);
    const data = await this.service.discardAutoGenerate(
      termId,
      deptId,
      req.user.id,
    );
    return { data };
  }

  @Auditable({ action: 'schedule.clear_auto_drafts', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Delete('auto-drafts')
  async clearAutoDrafts(
    @Query('termId') termId: string,
    @Query('deptId') queryDeptId: string | undefined,
    @Req() req: any,
  ) {
    const deptId = this.resolveDeptId(req, queryDeptId);
    const data = await this.service.clearAutoDrafts(termId, deptId);
    return { data };
  }

  // ═══════════════════════════════════════════════════════════
  // SCHEDULE VERSION ROUTES — FR 5.1.8(a)
  // ═══════════════════════════════════════════════════════════

  @Get('versions')
  @Roles('college_dean', 'department_head')
  async findVersions(@Query('termId') termId: string) {
    const data = await this.service.findVersions(termId);
    return { data };
  }

  @Get('versions/compare')
  @Roles('college_dean', 'department_head')
  async compareVersions(
    @Query('a') versionAId: string,
    @Query('b') versionBId: string,
  ) {
    const data = await this.service.compareVersions(versionAId, versionBId);
    return { data };
  }

  @Get('versions/:versionId')
  @Roles('college_dean', 'department_head')
  async findVersion(@Param('versionId') versionId: string) {
    const data = await this.service.findVersion(versionId);
    return { data };
  }

  // ═══════════════════════════════════════════════════════════
  // LIST ROUTES
  // ═══════════════════════════════════════════════════════════

  /**
   * List schedules.
   *
   * By default excludes rows whose dept is inactive. Dean can pass
   * `?includeInactive=true` (in addition to `?termId=`) to audit
   * or clean up inactive-dept data.
   */
  @Get()
  async findAll(
    @Query('termId') termId?: string,
    @Query('includeInactive') includeInactive?: string,
  ) {
    const includeInactiveDepts = includeInactive === 'true';
    const data = termId
      ? await this.service.findByTerm(termId, includeInactiveDepts)
      : await this.service.findAll(includeInactiveDepts);
    return { data };
  }

  @Get('room-sufficiency')
  @Roles('college_dean', 'department_head')
  async roomSufficiency(
    @Query('deptId') deptId?: string,
    @Query('termId') termId?: string,
  ) {
    const data = await this.service.getRoomSufficiency(deptId, termId);
    return { data };
  }

  // ═══════════════════════════════════════════════════════════
  // PARAMETERIZED (:id) ROUTES
  // ═══════════════════════════════════════════════════════════

  @Auditable({ action: 'schedule.update', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Patch(':id')
  async update(
    @Param('id') id: string,
    @Body() dto: UpdateScheduleDto,
    @Req() req: any,
  ) {
    return { data: await this.service.update(id, dto, req.profile) };
  }

  @Auditable({ action: 'schedule.status_change', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Patch(':id/status')
  async updateStatus(
    @Param('id') id: string,
    @Body() dto: UpdateStatusDto,
    @Req() req: any,
  ) {
    const data = await this.service.updateStatus(id, dto.status, req.profile);
    return { data };
  }

  @Roles('college_dean', 'department_head')
  @Patch(':id/remarks')
  async updateRemarks(
    @Param('id') id: string,
    @Body() dto: UpdateRemarksDto,
    @Req() req: any,
  ) {
    const data = await this.service.updateRemarks(
      id,
      dto.remarks ?? null,
      req.profile,
    );
    return { data };
  }

  @Auditable({ action: 'schedule.flag', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Post(':id/flag')
  async flag(
    @Param('id') id: string,
    @Body() dto: FlagScheduleDto,
    @Req() req: any,
  ) {
    const data = await this.service.flagSchedule(id, dto.reason, req.profile);
    return { data };
  }

  @Auditable({ action: 'schedule.unflag', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Delete(':id/flag')
  async unflag(@Param('id') id: string, @Req() req: any) {
    const data = await this.service.unflagSchedule(id, req.profile);
    return { data };
  }

  @Auditable({ action: 'schedule.delete', source: 'Scheduling' })
  @Roles('college_dean', 'department_head')
  @Delete(':id')
  async remove(@Param('id') id: string, @Req() req: any) {
    return this.service.remove(id, req.profile);
  }

    /**
   * Phase 2: resolve the department a lock-scoped route applies to.
   *
   * - DH: always their own dept, ignoring any override (defense-in-depth).
   * - Dean: must pass an explicit deptId (query or body); otherwise
   *   reject so we never touch a term-wide state by accident.
   */
  private resolveDeptId(req: any, override?: string): string {
    const isDH = req.profile?.role === 'department_head';
    if (isDH) {
      const myDept = req.profile?.deptId;
      if (!myDept) {
        throw new BadRequestException(
          'Your account is not linked to a department.',
        );
      }
      return String(myDept);
    }
    if (!override) {
      throw new BadRequestException(
        'deptId is required for Dean-initiated auto-generate actions.',
      );
    }
    return String(override);
  }
  
}
